const cache = new Map();
const stats = { generated: 0, ms: 0, perFamily: {} };

/** Create a CanvasTexture by drawing into a 2D context. draw(ctx, w, h). opts: {srgb=true, repeat, mipmaps=true, anisotropy=4, wrap} */
export function canvasTexture(w, h, draw, opts = {}) {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d', { willReadFrequently: !!opts.readback });
  draw(g, w, h);
  const t = new THREE.CanvasTexture(c);
  if (opts.srgb !== false) t.colorSpace = THREE.SRGBColorSpace;
  t.wrapS = t.wrapT = opts.wrap ?? THREE.RepeatWrapping;
  t.anisotropy = opts.anisotropy ?? 4;
  if (opts.mipmaps === false) {
    t.generateMipmaps = false;
    t.minFilter = THREE.LinearFilter;
  }
  if (opts.repeat) t.repeat.set(opts.repeat[0], opts.repeat[1]);
  return t;
}

// ---------------------------------------------------------------------------
// Quality: texture resolution scale (defaults follow the graphics preset).
// ---------------------------------------------------------------------------
const QUALITY_SCALE = { low: 0.5, medium: 0.5, high: 1, ultra: 1 };
let qualityOverride = null;
/** Force texture quality ('low'|'medium'|'high'|'ultra'); affects textures generated afterwards. */
export function setTextureQuality(q) {
  qualityOverride = q;
}
function qualityScale() {
  const q = qualityOverride || settings.get('graphicsPreset') || 'high';
  return QUALITY_SCALE[q] ?? 1;
}

const KEY_TO_FAMILY = new Map();
for (const f of FAMILIES) for (const k of f.keys) KEY_TO_FAMILY.set(k, f);
/** Every texture key tex() understands. */
export const TEXTURE_KEYS = FAMILIES.flatMap((f) => f.keys);

function makeTexture(key, raw) {
  const { w, h, data } = raw;
  // generators paint top-down (like a canvas); flip so v=1 is the image top, matching CanvasTexture.
  const row = w * 4;
  const flipped = new Uint8Array(data.length);
  for (let y = 0; y < h; y++) flipped.set(data.subarray(y * row, (y + 1) * row), (h - 1 - y) * row);
  const t = new THREE.DataTexture(flipped, w, h, THREE.RGBAFormat, THREE.UnsignedByteType);
  t.colorSpace = raw.srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace;
  const wrap = raw.wrap === 'clamp' ? THREE.ClampToEdgeWrapping : THREE.RepeatWrapping;
  t.wrapS = t.wrapT = wrap;
  if (raw.meta && raw.meta.nearest) {
    t.magFilter = t.minFilter = THREE.NearestFilter;
    t.generateMipmaps = false;
  } else {
    t.magFilter = THREE.LinearFilter;
    t.minFilter = THREE.LinearMipmapLinearFilter;
    t.generateMipmaps = true;
    t.anisotropy = 8;
  }
  t.name = key;
  t.userData = { key, alpha: !!raw.alpha, ...(raw.meta || {}) };
  t.needsUpdate = true;
  return t;
}

function familySize(f, opts) {
  if (f.fixed) return f.size;
  if (opts.size) return opts.size;
  const base = f.size ?? 512;
  return Math.max(f.minSize ?? 128, Math.round((base * qualityScale()) / 64) * 64);
}

function generate(f, size) {
  const t0 = performance.now();
  let raws;
  try {
    raws = f.gen(size);
  } catch (err) {
    console.error('[textures] generator failed for', f.keys[0], err);
    raws = {};
  }
  const ms = performance.now() - t0;
  stats.generated++;
  stats.ms += ms;
  stats.perFamily[f.keys[0] + '@' + size] = Math.round(ms);
  for (const k of f.keys) {
    const raw = raws[k];
    if (raw) cache.set(k + '@' + size, makeTexture(k, raw));
  }
}

const warned = new Set();
function fallback(key) {
  if (!warned.has(key)) {
    warned.add(key);
    console.warn(`[textures] unknown texture key "${key}"`);
  }
  const ck = 'fallback:' + key;
  let t = cache.get(ck);
  if (!t) {
    const isData = /_(normal|rough|mask|height)$/.test(key);
    const data = new Uint8Array(4 * 16);
    for (let i = 0; i < 16; i++) data.set(isData ? [128, 128, 255, 255] : [128, 120, 110, 255], i * 4);
    t = new THREE.DataTexture(data, 4, 4);
    t.wrapS = t.wrapT = THREE.RepeatWrapping;
    t.colorSpace = isData ? THREE.NoColorSpace : THREE.SRGBColorSpace;
    t.needsUpdate = true;
    cache.set(ck, t);
  }
  return t;
}

/**
 * Get a cached procedural texture by key (see TEXTURE_KEYS / docs), e.g.
 * 'asphalt', 'asphalt_normal', 'asphalt_rough', 'concrete_moss', 'bark', 'leaf_tropical' (RGBA atlas), ...
 * opts: { repeat:[u,v] } returns a clone sharing the image with its own repeat; { size } forces a resolution.
 * Colour maps are sRGB; *_normal / *_rough / masks / noise are NoColorSpace data maps.
 */
export function tex(key, opts = {}) {
  const f = KEY_TO_FAMILY.get(key);
  let t = photoLoaded('textures', key);
  if (t) {
    // photobashed (the size option is ignored: photo maps have fixed resolutions)
  } else if (!f) t = fallback(key);
  else {
    const size = familySize(f, opts);
    const ck = key + '@' + size;
    t = cache.get(ck);
    if (!t) {
      generate(f, size);
      t = cache.get(ck) || fallback(key);
    }
  }
  if (opts.repeat) {
    const c = t.clone();
    c.repeat.set(opts.repeat[0], opts.repeat[1]);
    c.needsUpdate = true;
    return c;
  }
  return t;
}

/** True if the key is usable without generation work (photo loaded, or family generated at this quality). */
export function isTextureReady(key) {
  if (photoLoaded('textures', key)) return true;
  const f = KEY_TO_FAMILY.get(key);
  return !!f && cache.has(key + '@' + familySize(f, {}));
}

/** True when tex(key) returns the photobashed texture (manifest entry loaded). */
export function hasPhotoTexture(key) {
  return !!photoLoaded('textures', key);
}

// ---------------------------------------------------------------------------
// Worker pool (pure generators run in parallel off the main thread during preload)
// ---------------------------------------------------------------------------
let pool = null;
function getPool() {
  if (pool !== null) return pool;
  try {
    if (typeof Worker === 'undefined') throw new Error('no workers');
    const n = Math.max(1, Math.min(4, (navigator.hardwareConcurrency || 4) - 1));
    pool = { workers: [], idle: [], queue: [], jobs: new Map(), nextId: 1 };
    for (let i = 0; i < n; i++) {
      const w = new Worker(new URL('./texture.worker.js', import.meta.url), { type: 'module' });
      w.onmessage = (e) => onWorkerMessage(w, e.data);
      w.onerror = (e) => {
        console.warn('[textures] worker error, falling back to main thread', e.message || e);
        // fail every job of this worker; preload falls back to sync generation
        for (const [id, job] of pool.jobs) if (job.worker === w) (pool.jobs.delete(id), job.resolve(false));
      };
      pool.workers.push(w);
      pool.idle.push(w);
    }
  } catch (err) {
    pool = false;
  }
  return pool;
}
function pump() {
  while (pool && pool.idle.length && pool.queue.length) {
    const job = pool.queue.shift();
    const w = pool.idle.pop();
    job.worker = w;
    pool.jobs.set(job.id, job);
    w.postMessage({ id: job.id, key: job.fam.keys[0], size: job.size });
  }
}
function onWorkerMessage(w, msg) {
  const job = pool.jobs.get(msg.id);
  pool.idle.push(w);
  if (job) {
    pool.jobs.delete(msg.id);
    if (msg.ok) {
      stats.generated++;
      stats.ms += msg.ms;
      stats.perFamily[job.fam.keys[0] + '@' + job.size] = Math.round(msg.ms) + 'w';
      for (const k of job.fam.keys) {
        const raw = msg.raws[k];
        const ck = k + '@' + job.size;
        if (raw && !cache.has(ck)) cache.set(ck, makeTexture(k, raw));
      }
      job.resolve(true);
    } else {
      console.warn('[textures] worker generator failed', job.fam.keys[0], msg.error);
      job.resolve(false);
    }
  }
  pump();
}
function runInWorker(fam, size) {
  return new Promise((resolve) => {
    pool.queue.push({ id: pool.nextId++, fam, size, resolve });
    pump();
  });
}
/** Terminate the worker pool (it is re-created on the next preload). */
export function disposeTextureWorkers() {
  if (pool) for (const w of pool.workers) w.terminate();
  pool = null;
}

const yieldFrame = () => new Promise((r) => setTimeout(r, 0));

/**
 * Warm up the library (call once at boot / behind a loading screen, before the world is built):
 *  1. fetch public/assets/textures/manifest.json and load the photobashed maps of the requested keys
 *     (and, by default, every printed / decal image), in parallel;
 *  2. generate the procedural families that photos do not fully cover, in a Web Worker pool
 *     (canvas-based ones on the main thread between yields).
 * keys default to TEXTURE_KEYS. onProgress(done, total, key).
 * opts: { workers=true, photos=true, printed=(keys === TEXTURE_KEYS) }.
 * tex() never waits: before this resolves it returns procedural textures (generated synchronously).
 */
export async function preloadTextures(keys = TEXTURE_KEYS, onProgress = null, opts = {}) {
  const usePhotos = opts.photos !== false && photoTexturesEnabled();
  if (usePhotos) await loadPhotoManifest();
  const fams = [];
  for (const k of keys) {
    const f = KEY_TO_FAMILY.get(k);
    if (f && !fams.includes(f)) fams.push(f);
  }
  // photo files to load: every family key with a manifest entry (companions included so the
  // colour / normal / rough set always comes from the same source), plus photo-only keys
  const photoKeys = new Set();
  const covered = new Set();
  if (usePhotos) {
    for (const f of fams) {
      const have = f.keys.filter((k) => photoEntry('textures', k));
      for (const k of have) photoKeys.add(k);
      if (have.length === f.keys.length) covered.add(f);
    }
    for (const k of keys) if (!KEY_TO_FAMILY.has(k) && photoEntry('textures', k)) photoKeys.add(k);
  }
  const extras = [];
  const wantPrinted = opts.printed ?? keys === TEXTURE_KEYS;
  if (usePhotos && wantPrinted) {
    const m = photoManifest();
    for (const k of Object.keys(m.printed || {})) extras.push(['printed', k]);
    const reduced = settings.get('gore') === 'reduced';
    for (const k of Object.keys(m.decals || {})) if (k.endsWith(':reduced') === reduced) extras.push(['decals', k]);
  }
  const photoList = [...photoKeys].filter((k) => !photoLoaded('textures', k)).map((k) => ['textures', k]);
  let done = 0;
  const total = fams.length + photoList.length + extras.length;
  const tick = (key) => {
    done++;
    if (onProgress) onProgress(done, total, key);
  };
  const scale = qualityScale();
  const photoJob = usePhotos
    ? loadPhotos(photoList.concat(extras), { scale, onEach: (d, t, key) => tick(key) })
    : Promise.resolve();

  const ready = (f) => cache.has(f.keys[0] + '@' + familySize(f, {}));
  const todo = fams.filter((f) => !ready(f) && !covered.has(f));
  for (const f of fams) if (!todo.includes(f)) tick(f.keys[0]);
  const p = opts.workers === false ? false : getPool();
  const main = [];
  const jobs = [];
  for (const f of todo) {
    if (p && !f.dom) {
      jobs.push(
        runInWorker(f, familySize(f, {})).then(async (ok) => {
          if (!ok && !ready(f)) {
            await yieldFrame();
            generate(f, familySize(f, {}));
          }
          tick(f.keys[0]);
        }),
      );
    } else main.push(f);
  }
  for (const f of main) {
    if (!ready(f)) generate(f, familySize(f, {}));
    tick(f.keys[0]);
    await yieldFrame();
  }
  await Promise.all(jobs);
  await photoJob;
  // a covered family whose photo failed to load falls back to procedural generation
  for (const f of covered) {
    if (f.keys.some((k) => !photoLoaded('textures', k)) && !ready(f)) {
      generate(f, familySize(f, {}));
      await yieldFrame();
    }
  }
}

/**
 * Pre-draw sign textures (main thread, yielding between them). list: [[kind, opts], ...].
 * onProgress(done, total, kind).
 */
export async function preloadSigns(list, onProgress = null) {
  let i = 0;
  for (const [kind, o] of list) {
    signTex(kind, o || {});
    i++;
    if (onProgress) onProgress(i, list.length, kind);
    await yieldFrame();
  }
}

/** Timing stats {generated, ms, perFamily:{key@size: ms}, photo:{files, bytes, ms, failed}}. */
export function textureStats() {
  return { ...stats, perFamily: { ...stats.perFamily }, photo: { ...photoStats } };
}

/**
 * Signage / decals / printed matter as CanvasTextures (original fictional Thai designs).
 * kind: 'km_marker' {km}, 'curve_warning' {dir}, 'elephant_crossing', 'village_sign' {th,en},
 *   'shrine_board', 'couplet' {text}, 'taxi_roof', 'vacant_lamp', 'plate' {text, province}, 'sticker' {variant},
 *   'poster' {variant}, 'drink_label' {variant}, 'snack_wrapper' {variant}, 'receipt' {lines}, 'lottery',
 *   'calendar', 'noodle_menu', 'garage_sign', 'bus_stop_sign', 'temple_sign', 'fork_sign' {side:'left'|'right'},
 *   'amulet_face', 'buddha_card', 'speed_sign' {kmh}, 'warning_sign' {th,en}, 'shop_sign' {th,en}
 * Common opts: { weather=1 (multiplier on the ageing: 0 = pristine, 1.5 = ruined) }.
 * Returned texture.userData: { kind, aspect (w/h), alpha (true when the shape is cut out by alpha),
 *   shape ('rect'|'diamond'|'diamond_plate'|'circle'|'arrow'|'strip'|'sticker'|'tablet'),
 *   size:[metres w,h] suggested physical size, normalMap? (relief items like amulet_face) }.
 * Shapes are drawn upright: use an axis-aligned quad of `aspect` with alphaTest (don't rotate diamonds 45°).
 */
export function signTex(kind, opts = {}) {
  const key = 'sign:' + kind + ':' + JSON.stringify(opts);
  if (cache.has(key)) return cache.get(key);
  const pk = photoSignKey(kind, opts);
  if (pk) {
    const t = photoPrinted('printed', pk, kind, opts);
    cache.set(key, t);
    return t;
  }
  const t0 = performance.now();
  const t = drawSign(kind, opts);
  stats.perFamily[key] = Math.round(performance.now() - t0);
  t.name = key;
  cache.set(key, t);
  return t;
}

