const PHOTO_OK_OPTS = new Set(['variant', 'weather', 'photo', 'km', 'kmh', 'dir']);
// plain calls of these procedural kinds use their photobashed default (similar physical size / aspect)
const PHOTO_DEFAULT = { calendar: 'buddha', noodle_menu: 'board', lottery: 'temple', receipt: 'taxi' };
const PHOTO_ALIAS = { 'drink_label:red_soda': 'soda_red', 'drink_label:energy': 'energy' };

/** 'kind:variant' of the photobashed version that can honour these opts, or null (-> procedural). */
function photoSignKey(kind, opts) {
  if (opts.photo === false || !photoTexturesEnabled()) return null;
  for (const k of Object.keys(opts)) if (!PHOTO_OK_OPTS.has(k)) return null; // custom text etc.
  let pkind = kind;
  let variant = opts.variant;
  if (kind === 'km_marker') variant = String(opts.km ?? 9);
  else if (kind === 'curve_warning') (pkind = 'road_sign'), (variant = opts.dir === 'left' ? 'curve_left' : 'curve_right');
  else if (kind === 'speed_sign') (pkind = 'road_sign'), (variant = 'speed_' + (opts.kmh ?? 60));
  const cat = PRINTED_CATALOGUE[pkind];
  if (!cat) return null;
  if (variant == null) {
    if (PHOTO_DEFAULT[kind]) variant = PHOTO_DEFAULT[kind];
    else if (PROC_SIGN_KINDS[kind]) return null; // plain procedural call: keep the canvas design
    else variant = cat.variants[0];
  }
  variant = PHOTO_ALIAS[pkind + ':' + variant] ?? variant;
  return cat.variants.includes(String(variant)) ? pkind + ':' + variant : null;
}

/** Swap the photo into a placeholder texture once the manifest (and the file) are available. */
function fillWhenReady(section, pk, t) {
  if (!photoTexturesEnabled()) return;
  const go = () => {
    if (photoEntry(section, pk)) loadPhoto(section, pk, { into: t });
  };
  if (photoManifest()) go();
  else loadPhotoManifest().then(go);
}

/** Texture for a printed / decal photo entry: the loaded image, or a placeholder filled on arrival. */
function photoPrinted(section, pk, kind, opts) {
  const [pkind, variant] = pk.split(':');
  const cat = PRINTED_CATALOGUE[pkind];
  const e = photoEntry(section, pk);
  const size = (cat && cat.sizes && cat.sizes[variant]) || (e && e.size) || [0.5, 0.5];
  const aspect = e ? e.aspect || size[0] / size[1] : size[0] / size[1];
  const shape = (e && e.shape) || SHAPES[kind] || 'rect';
  let t = photoLoaded(section, pk);
  if (!t) {
    // procedural stand-in until the file arrives (same aspect intent); the image is swapped in place
    const fb = cat && cat.fallback && cat.fallback[variant];
    t = fb && (PROC_SIGN_KINDS[fb[0]] || fb[0] === 'sticker' || fb[0] === 'poster') ? drawSign(fb[0], fb[1] || {}) : drawSign(kind, {});
    fillWhenReady(section, pk, t);
  }
  t.userData = { ...(t.userData || {}), kind, variant, aspect, alpha: !!(e ? e.alpha : t.userData?.alpha), size, shape, photo: true };
  return t;
}

/**
 * RGBA decal texture (alpha-blend or alphaTest it on a quad / projected decal).
 * kind: 'blood_pool' | 'blood_smear' | 'blood_spatter' | 'blood_handprint' | 'blood_drip' (opts.variant 0..n),
 *       or any printed kind with decal:true in PRINTED_CATALOGUE ('poster', 'sticker', 'newspaper', 'receipt',
 *       'snack_bag', 'joss_paper', 'offering_label', 'fare_chart', 'lottery') with opts.variant.
 * blood_*: when settings.gore === 'reduced' the darker, sparser twin is returned (opts.gore overrides).
 * userData: { kind, variant, aspect, size:[w,h] metres, alpha:true, gore? }. blood_drip tiles in u.
 */
export function decalTex(kind, opts = {}) {
  const def = DECAL_KINDS[kind];
  const variant = String(opts.variant ?? (def ? def.variants[0] : 0));
  const blood = kind.startsWith('blood_');
  const reduced = blood && (opts.gore ?? settings.get('gore')) === 'reduced';
  const key = 'decal:' + kind + ':' + variant + (reduced ? ':reduced' : '');
  if (cache.has(key)) return cache.get(key);
  let t;
  if (blood) {
    const pk = kind + ':' + variant + (reduced ? ':reduced' : '');
    t = photoLoaded('decals', pk);
    if (!t) {
      t = bloodFallback(kind, Number(variant) || 0, reduced);
      fillWhenReady('decals', pk, t);
    }
    const size = def ? def.size : [0.5, 0.5];
    const e = photoEntry('decals', pk);
    t.userData = { ...(t.userData || {}), kind, variant, aspect: e ? e.aspect : size[0] / size[1], size, alpha: true, gore: reduced ? 'reduced' : 'full' };
    if (kind === 'blood_drip' && t.wrapS !== THREE.RepeatWrapping) {
      t.wrapS = THREE.RepeatWrapping;
      t.needsUpdate = true;
    }
  } else {
    const cat = PRINTED_CATALOGUE[kind];
    const v = cat && cat.variants.includes(variant) ? variant : cat ? cat.variants[0] : null;
    t = v != null ? photoPrinted('printed', kind + ':' + v, kind, opts) : drawSign(kind, { variant });
    t.userData = { ...t.userData, alpha: true };
  }
  t.name = key;
  cache.set(key, t);
  return t;
}

/** Procedural stand-in for blood decals (until / unless the photobashed file loads). */
function bloodFallback(kind, variant, reduced) {
  const drip = kind === 'blood_drip';
  return canvasTexture(drip ? 128 : 256, 256, (g, w, h) => {
    let seed = (variant + 1) * 9301 + kind.length * 49297;
    const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
    g.clearRect(0, 0, w, h);
    g.fillStyle = reduced ? '#2a0606' : '#4a0808';
    if (drip) {
      g.fillRect(0, 0, w, 10);
      for (let i = 0; i < 7; i++) {
        const x = rnd() * w, len = h * (0.2 + rnd() * 0.7), r = 2 + rnd() * 3;
        g.fillRect(x - r / 2, 0, r, len);
        g.beginPath();
        g.arc(x, len, r * 1.4, 0, Math.PI * 2);
        g.fill();
      }
      return;
    }
    const n = kind === 'blood_spatter' ? 60 : kind === 'blood_pool' ? 9 : 14;
    for (let i = 0; i < n; i++) {
      const a = rnd() * Math.PI * 2, d = rnd() * (kind === 'blood_pool' ? 50 : 100);
      const r = kind === 'blood_spatter' ? 2 + rnd() * 6 : 14 + rnd() * 30;
      g.beginPath();
      g.ellipse(w / 2 + Math.cos(a) * d, h / 2 + Math.sin(a) * d, r, r * (0.6 + rnd() * 0.4), a, 0, Math.PI * 2);
      g.fill();
    }
  }, { wrap: THREE.ClampToEdgeWrapping });
}
