// Internals: photo.js (manifest + image loading), noise.js / painter.js (procedural painting),
// mat_*.js (material families), foliage.js (leaf atlases), road.js (road markings), signs.js /
// printed.js (canvas signage), flowerLayout.js / printedCatalogue.js (generated by tools/photobash).
