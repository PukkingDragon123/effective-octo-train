/**
 * Photobashed world foliage atlas tex('foliage_world'): the SAME 5x5 slot layout as
 * src/world/foliageAtlas.js (slot i at column i % 5, row floor(i / 5) from the top; slot = 1/5 of the
 * texture; base at the slot's bottom centre, vines hang from the top, banana midribs run bottom->top).
 * Swap it in only when hasPhotoTexture('foliage_world') (its procedural fallback is transparent).
 */
export const WORLD_FOLIAGE = {
  key: 'foliage_world',
  normalKey: 'foliage_world_normal',
  grid: 5,
  slots: ['broadA', 'broadB', 'rain', 'fig', 'bamboo', 'banana', 'bananaDead', 'palm', 'fern', 'grass',
    'elephant', 'vines', 'shrub', 'deadTwigs', 'epiphyte', 'tallGrass', 'small', 'smallDark'],
  /** uv rect {u0,v0,u1,v1} of a slot index or name (same as world slotRect, inset 1 texel at 2048). */
  rect(slot) {
    const i = typeof slot === 'string' ? this.slots.indexOf(slot) : slot;
    const g = this.grid, x = i % g, y = Math.floor(i / g), e = 1 / 2048;
    return { u0: x / g + e, u1: (x + 1) / g - e, v0: 1 - (y + 1) / g + e, v1: 1 - y / g - e };
  },
};

/** Flower atlas cell lookup: flowerCell('marigold', 'front', wilted=false) -> FLOWER_ATLAS cell (or null). */
export function flowerCell(name, view = 'front', wilted = false) {
  const n = wilted && !name.endsWith('_wilted') ? name + '_wilted' : name;
  return FLOWER_ATLAS.cells.find((c) => c.name === n && c.view === view) ||
    FLOWER_ATLAS.cells.find((c) => c.name === name && c.view === view) || null;
}

