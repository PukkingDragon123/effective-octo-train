// Texture library (contract: docs/ARCHITECTURE.md "textures").
//
//   tex(key, {repeat, size})   photobashed texture when loaded (public/assets/textures), else the
//                              cached procedural DataTexture (lazy: generated on first use)
//   signTex(kind, opts)        Thai signage / printed matter / packaging (photobashed variants + canvas)
//   decalTex(kind, opts)       RGBA decals: stickers, posters, paper bits, blood_* (gore-setting aware)
//   canvasTexture(w,h,draw,opts), fontsReady(), FONTS
//   FOLIAGE_ATLAS, WORLD_FOLIAGE, FLOWER_ATLAS, ROAD_MARKINGS   uv layouts of the atlas textures
//   preloadTextures(keys, onProgress, opts)   async warm-up: photo manifest + photo files, procedural
